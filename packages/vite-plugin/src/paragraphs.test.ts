import { describe, expect, it } from 'bun:test';
import { join } from 'node:path';
import type { Rollup } from 'vite';
import { fixture } from '../../../tools/lib/fixture';
import { emitParagraphTables } from './paragraphs';

/** A device module of the fixture, as the shader build writes it: it names its target's table. */
const MODULE = `// Generated by the shader build.
import { SHARED_0 } from './shader-paragraphs-wgsl.js';

export const SHADERS = {};
`;

/** The table of the fixture. */
const TABLE = 'export const SHARED_0 = `uniform vec4 shared;`;\n';

/**
 * A device module that holds paragraphs of its own feature family: it names its kind's table and
 * the family's, as the shader build writes them.
 */
const FAMILY_MODULE = `// Generated by the shader build.
import { SHARED_0 } from './shader-paragraphs-wgsl.js';
import { MORPH_SHARED_0 } from './shader-paragraphs-wgsl-morph.js';

export const SHADERS = {};
`;

/** A first import long enough to push the family's import past the first window that is read. */
const LONG_MODULE = `// Generated by the shader build.
import { ${Array.from({ length: 800 }, (_, index) => `SHARED_${index}`).join(', ')} } from './shader-paragraphs-wgsl.js';
import { MORPH_SHARED_0 } from './shader-paragraphs-wgsl-morph.js';

export const SHADERS = {};
`;

const root = fixture({
	'engine/generated/shaders-skinning-wgsl.js': MODULE,
	'engine/generated/shaders-skinning-glsl-half.js': MODULE,
	'engine/generated/shaders-skinning-wgsl-morph.js': FAMILY_MODULE,
	'engine/generated/shaders-skinning-wgsl-long.js': LONG_MODULE,
	'engine/generated/shader-paragraphs-wgsl.js': TABLE,
	'engine/generated/shader-paragraphs-wgsl-morph.js': TABLE,
	'engine/generated/shader-paragraphs-glsl-half.js': TABLE,
});

const asset = (fileName: string, source: string, originalFileNames: string[]) =>
	({ type: 'asset', fileName, source, originalFileNames }) as unknown as Rollup.OutputAsset;

/** The plain device module and where the fixture holds it. */
const MODULE_OF = { path: 'engine/generated/shaders-skinning-wgsl.js', text: MODULE };

const moduleOf = (fileName: string, module: { path: string; text: string } = MODULE_OF) =>
	asset(fileName, module.text, [join(root, module.path)]);

const bundleOf = (...files: Rollup.OutputAsset[]) =>
	Object.fromEntries(files.map((file) => [file.fileName, file])) as Rollup.OutputBundle;

/** A plugin context that records what the plugin emits, and throws on a build error. */
function context(emitted: { fileName: string; source: string }[]) {
	return {
		emitFile(file: { fileName: string; source: unknown }) {
			emitted.push({ fileName: file.fileName, source: String(file.source) });
			return 'reference';
		},
		error(message: string): never {
			throw new Error(message);
		},
	} as unknown as Rollup.PluginContext;
}

describe('emitParagraphTables', () => {
	it('emits the table beside the module that names it, and gives the files of each', () => {
		const emitted: { fileName: string; source: string }[] = [];
		const tables = emitParagraphTables.call(
			context(emitted),
			bundleOf(moduleOf('assets/shaders-skinning-wgsl-a1.js')),
		);
		expect([...tables]).toEqual([
			['assets/shaders-skinning-wgsl-a1.js', ['assets/shader-paragraphs-wgsl.js']],
		]);
		expect(emitted).toEqual([{ fileName: 'assets/shader-paragraphs-wgsl.js', source: TABLE }]);
	});

	it('finds a table beside a module that the build names relative to its root', () => {
		const emitted: { fileName: string; source: string }[] = [];
		const relative = asset('assets/shaders-skinning-wgsl-a1.js', MODULE, [
			'engine/generated/shaders-skinning-wgsl.js',
		]);
		expect([...emitParagraphTables.call(context(emitted), bundleOf(relative), root)]).toEqual([
			['assets/shaders-skinning-wgsl-a1.js', ['assets/shader-paragraphs-wgsl.js']],
		]);
		expect(emitted).toEqual([{ fileName: 'assets/shader-paragraphs-wgsl.js', source: TABLE }]);
	});

	it('emits every table that a module of a feature family names', () => {
		const emitted: { fileName: string; source: string }[] = [];
		const family = moduleOf('assets/shaders-skinning-wgsl-morph-a1.js', {
			path: 'engine/generated/shaders-skinning-wgsl-morph.js',
			text: FAMILY_MODULE,
		});
		expect([...emitParagraphTables.call(context(emitted), bundleOf(family))]).toEqual([
			[
				'assets/shaders-skinning-wgsl-morph-a1.js',
				['assets/shader-paragraphs-wgsl.js', 'assets/shader-paragraphs-wgsl-morph.js'],
			],
		]);
		expect(emitted.map((file) => file.fileName).sort()).toEqual([
			'assets/shader-paragraphs-wgsl-morph.js',
			'assets/shader-paragraphs-wgsl.js',
		]);
	});

	it('reads past a first import too long for the first window', () => {
		const emitted: { fileName: string; source: string }[] = [];
		const long = moduleOf('assets/shaders-skinning-wgsl-long-a1.js', {
			path: 'engine/generated/shaders-skinning-wgsl-long.js',
			text: LONG_MODULE,
		});
		expect([...emitParagraphTables.call(context(emitted), bundleOf(long))]).toEqual([
			[
				'assets/shaders-skinning-wgsl-long-a1.js',
				['assets/shader-paragraphs-wgsl.js', 'assets/shader-paragraphs-wgsl-morph.js'],
			],
		]);
	});

	it('follows a table whose name carries the bits that a device fixes', () => {
		const emitted: { fileName: string; source: string }[] = [];
		const half = asset(
			'assets/shaders-skinning-glsl-half-b2.js',
			"import { SHARED_0 } from './shader-paragraphs-glsl-half.js';\n",
			[join(root, 'engine/generated/shaders-skinning-glsl-half.js')],
		);
		expect([...emitParagraphTables.call(context(emitted), bundleOf(half))]).toEqual([
			['assets/shaders-skinning-glsl-half-b2.js', ['assets/shader-paragraphs-glsl-half.js']],
		]);
		expect(emitted.map((file) => file.fileName)).toEqual(['assets/shader-paragraphs-glsl-half.js']);
	});

	it('emits the table once however many modules of its folder name it', () => {
		const emitted: { fileName: string; source: string }[] = [];
		const tables = emitParagraphTables.call(
			context(emitted),
			bundleOf(
				moduleOf('assets/shaders-skinning-wgsl-a1.js'),
				moduleOf('assets/shaders-skinning-wgsl-b2.js'),
			),
		);
		expect(emitted).toHaveLength(1);
		expect(tables.size).toBe(2);
	});

	it('emits the table in each folder that holds a module that names it', () => {
		const emitted: { fileName: string; source: string }[] = [];
		emitParagraphTables.call(
			context(emitted),
			bundleOf(
				moduleOf('assets/shaders-skinning-wgsl-a1.js'),
				moduleOf('assets/workers/shaders-skinning-wgsl-b2.js'),
			),
		);
		expect(emitted.map((file) => file.fileName).sort()).toEqual([
			'assets/shader-paragraphs-wgsl.js',
			'assets/workers/shader-paragraphs-wgsl.js',
		]);
	});

	it('leaves a module that names no table alone', () => {
		const emitted: { fileName: string; source: string }[] = [];
		const plain = asset('assets/shaders-glsl-a1.js', 'export const SHADERS = {};\n', [
			join(root, 'engine/generated/shaders-skinning-wgsl.js'),
		]);
		expect(emitParagraphTables.call(context(emitted), bundleOf(plain)).size).toBe(0);
		expect(emitted).toEqual([]);
	});

	it('fails the build when the engine holds no such table', () => {
		const emitted: { fileName: string; source: string }[] = [];
		const missing = asset('assets/shaders-skinning-wgsl-a1.js', MODULE, [
			join(root, 'absent', 'shaders-skinning-wgsl.js'),
		]);
		expect(() => emitParagraphTables.call(context(emitted), bundleOf(missing))).toThrow(
			'shader-paragraphs-wgsl.js',
		);
	});
});
