// The build that the add-on check reads its figures from: a production build of the fixture's page,
// with the source maps that name each function. The page links the engine's shader files as the
// files that the shader build wrote, so the build holds the engine's code alone. A map that
// embedded each source's text would still copy that code, and this check holds the maps small.
// The heavy run's memory ceiling holds the build to the figure that its own run measured.
import { describe, expect, test } from 'bun:test';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { scaledBudget } from '../../../tests/lib/run-budget.ts';
import { startBuildServer } from './server.js';

/** The fixture's page, which imports the engine and starts a sketch. */
const FIXTURE = join(import.meta.dirname, '../../../tests/fixtures/d9-addon');

/** The paths of the source maps under `folder`. */
function mapFiles(folder: string): string[] {
	const maps: string[] = [];
	for (const entry of readdirSync(folder, { withFileTypes: true })) {
		const path = join(folder, entry.name);
		if (entry.isDirectory()) maps.push(...mapFiles(path));
		else if (entry.name.endsWith('.map')) maps.push(path);
	}
	return maps;
}

/**
 * The paths of the scripts under `folder` that the build wrote, which are the files that the shader
 * set's own files sit beside.
 */
function builtScripts(folder: string): string[] {
	const scripts: string[] = [];
	for (const entry of readdirSync(folder, { withFileTypes: true })) {
		const path = join(folder, entry.name);
		if (entry.isDirectory()) scripts.push(...builtScripts(path));
		else if (entry.name.endsWith('.js') && !/^shaders?-/.test(entry.name)) scripts.push(path);
	}
	return scripts;
}

describe('a page build with source maps', () => {
	test(
		'writes a map for each built file, holds them small, and links the engine shader files',
		async () => {
			const cwd = process.cwd();
			process.chdir(FIXTURE);
			try {
				const server = await startBuildServer({ sourcemap: true, linkedShaders: true });
				try {
					// The engine's shader files take their place in the build as files that the shader build
					// wrote, beside the scripts that name them, rather than passing through the bundler.
					const build = server.buildDir as string;
					const assets = readdirSync(join(build, 'assets'));
					// Each name carries the shader set's stamp, so a page or a CDN may keep it.
					const shaderName = assets.find((name) => /^shaders-wgsl-[0-9a-f]{8}\.js$/.test(name));
					expect(shaderName).toBeDefined();
					const shader = readFileSync(join(build, 'assets', shaderName ?? ''), 'utf8');
					expect(shader.startsWith('// Generated by')).toBe(true);
					// No plain copy is left, so every shader address carries the stamp.
					expect(assets).not.toContain('shaders-wgsl.js');
					const maps = mapFiles(build);
					expect(maps.length).toBeGreaterThan(0);
					let bytes = 0;
					for (const path of maps) {
						const map = JSON.parse(readFileSync(path, 'utf8'));
						expect(map.sources.length).toBeGreaterThan(0);
						expect(map.mappings.length).toBeGreaterThan(0);
						bytes += statSync(path).size;
					}
					// The gate reads each mapping and each source's path, never a source's text, and a map
					// that carried the text would copy the build's code. The maps of a build that carried it
					// made 10 MB.
					expect(bytes).toBeLessThan(64 * 1024 * 1024);
					// A script of the build names the shader file at the address where the linked file now
					// sits, so a page that loads the build fetches what the shader build wrote.
					expect(
						builtScripts(build).some((path) =>
							readFileSync(path, 'utf8').includes(`./${shaderName}`),
						),
					).toBe(true);
				} finally {
					await server.close();
				}
			} finally {
				process.chdir(cwd);
			}
		},
		scaledBudget(600_000),
	);
});
