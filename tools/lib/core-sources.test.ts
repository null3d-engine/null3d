import { describe, expect, it } from 'bun:test';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import type { Connect, ViteDevServer } from 'vite';
import { hashFiles } from './build-cache';
import {
	acceptedSourcesStamps,
	coreFromOtherSources,
	coreSourcesServer,
	coreSourcesStamp,
	refuseStaleCore,
	STAMP_MODULE,
	stampGlue,
} from './core-sources';
import { fixture } from './fixture';
import { inputFiles, inputHash } from './shader-modules';

/** The crate that the engine core is built from, as the tools name it. */
const CORE_CRATE = 'crates/null3d-wasm';
/** A lock that resolves the core's closure, and holds a crate outside it. */
const LOCK = [
	'# This file is automatically @generated by Cargo.',
	'# It is not intended for manual editing.',
	'version = 4',
	'',
	'[[package]]',
	'name = "null3d-wasm"',
	'version = "0.1.0"',
	'dependencies = [',
	' "null3d-core",',
	']',
	'',
	'[[package]]',
	'name = "null3d-core"',
	'version = "0.1.0"',
	'',
	'[[package]]',
	'name = "null3d-shaders"',
	'version = "0.1.0"',
	'',
].join('\n');

/** A repository with the core's crate, its path dependency and a crate that it does not use. */
function repository(): string {
	return fixture({
		'Cargo.toml': '[workspace]\n',
		'Cargo.lock': LOCK,
		'rust-toolchain.toml': '',
		'crates/null3d-wasm/Cargo.toml':
			'[package]\nname = "null3d-wasm"\n\n[dependencies]\ncore = { path = "../null3d-core" }\n',
		'crates/null3d-wasm/src/lib.rs': '',
		'crates/null3d-core/Cargo.toml': '[package]\nname = "null3d-core"\n',
		'crates/null3d-core/src/lib.rs': '',
		'crates/null3d-core/tests/rows.rs': '',
		'crates/null3d-shaders/Cargo.toml': '[package]\nname = "null3d-shaders"\n',
		'crates/null3d-shaders/src/lib.rs': '',
	});
}

/** What the dev server answers to a request for `url`: the body it sends, or undefined to pass it on. */
function devServer(root: string): (url: string) => string | undefined {
	let handle: Connect.NextHandleFunction = () => undefined;
	const server = { middlewares: { use: (h: typeof handle) => (handle = h) } };
	const plugin = coreSourcesServer(root);
	(plugin.configureServer as (s: ViteDevServer) => void)(server as unknown as ViteDevServer);
	return (url) => {
		let body: string | undefined;
		const res = { setHeader: () => undefined, end: (text: string) => (body = text) };
		handle({ url } as Connect.IncomingMessage, res as never, () => undefined);
		return body;
	};
}

describe('the stamp of the core sources', () => {
	it('changes with the sources of the core and its path dependencies only', () => {
		const root = repository();
		const before = coreSourcesStamp(root);
		expect(before).toMatch(/^[0-9a-f]{16}$/);
		writeFileSync(join(root, 'crates/null3d-core/tests/rows.rs'), '// another test\n');
		writeFileSync(join(root, 'crates/null3d-shaders/src/lib.rs'), 'pub const A: u32 = 1;\n');
		expect(coreSourcesStamp(root)).toBe(before);
		writeFileSync(join(root, 'crates/null3d-core/src/lib.rs'), 'pub const A: u32 = 1;\n');
		expect(coreSourcesStamp(root)).not.toBe(before);
	});

	it('reads every input whole, so a core built before the cache narrowed its lock matches', () => {
		const root = repository();
		expect(coreSourcesStamp(root)).toBe(hashFiles(root, inputFiles(root, CORE_CRATE)).slice(0, 16));
	});

	it('goes into a generated module as an export', async () => {
		const text = stampGlue('export function batchArrays() { return 0; }\n', '0123456789abcdef');
		const glue = (await import(`data:text/javascript,${encodeURIComponent(text)}`)) as {
			coreSources: string;
		};
		expect(glue.coreSources).toBe('0123456789abcdef');
	});
});

describe('the dev server', () => {
	it('serves the stamps that a core of the checkout may carry, and passes other requests on', () => {
		const root = repository();
		const serve = devServer(root);
		const module = `export const CORE_SOURCES = ${JSON.stringify(acceptedSourcesStamps(root))};\n`;
		expect(serve(`/${STAMP_MODULE}`)).toBe(module);
		expect(serve(`/@fs${root}/${STAMP_MODULE}?import`)).toBe(module);
		expect(serve('/packages/engine/src/shared/core.ts')).toBeUndefined();
	});

	it('serves the current stamp and the earlier stamp while the transition lasts', () => {
		const root = repository();
		const text = devServer(root)(`/${STAMP_MODULE}`) ?? '';
		expect(text).toContain(coreSourcesStamp(root));
		expect(text).toContain(inputHash(root, CORE_CRATE).slice(0, 16));
	});

	it('serves the new stamps once the core sources change', () => {
		const root = repository();
		const serve = devServer(root);
		const before = serve(`/${STAMP_MODULE}`);
		writeFileSync(join(root, 'crates/null3d-wasm/src/lib.rs'), 'pub const A: u32 = 1;\n');
		const after = serve(`/${STAMP_MODULE}`);
		expect(after).not.toBe(before);
		expect(after).toContain(coreSourcesStamp(root));
	});
});

/** A checkout with the core's crate and no built core yet. */
const checkout = () => repository();
/** Writes a built core whose glue carries `stamp`. */
const buildCore = (root: string, stamp: string) => {
	for (const build of ['single', 'threaded']) {
		const glue = join(root, `packages/engine/dist/wasm/${build}/null3d.js`);
		mkdirSync(dirname(glue), { recursive: true });
		writeFileSync(glue, stampGlue('export {};\n', stamp));
	}
};

describe('the core that a page build ships', () => {
	it('accepts the cores that this checkout built', () => {
		const root = checkout();
		buildCore(root, coreSourcesStamp(root));
		expect(coreFromOtherSources(root)).toBeNull();
	});

	it('accepts a core that the build wrote before the cache narrowed its lock', () => {
		const root = checkout();
		buildCore(root, hashFiles(root, inputFiles(root, CORE_CRATE)).slice(0, 16));
		expect(coreFromOtherSources(root)).toBeNull();
	});

	it('accepts a core that the narrowed-lock key wrote, while the transition lasts', () => {
		const root = checkout();
		const earlier = inputHash(root, CORE_CRATE).slice(0, 16);
		expect(earlier).not.toBe(coreSourcesStamp(root));
		buildCore(root, earlier);
		expect(coreFromOtherSources(root)).toBeNull();
	});

	it('refuses an earlier stamp after a lock edit inside the core closure', () => {
		const root = checkout();
		const earlier = inputHash(root, CORE_CRATE).slice(0, 16);
		buildCore(root, earlier);
		writeFileSync(
			join(root, 'Cargo.lock'),
			LOCK.replace(
				'name = "null3d-core"\nversion = "0.1.0"',
				'name = "null3d-core"\nversion = "0.2.0"',
			),
		);
		expect(inputHash(root, CORE_CRATE).slice(0, 16)).not.toBe(earlier);
		expect(coreFromOtherSources(root)).toContain('the single engine core');
	});

	it('accepts an earlier stamp after a lock edit outside the core closure', () => {
		const root = checkout();
		const earlier = inputHash(root, CORE_CRATE).slice(0, 16);
		const whole = coreSourcesStamp(root);
		buildCore(root, earlier);
		writeFileSync(
			join(root, 'Cargo.lock'),
			LOCK.replace(
				'name = "null3d-shaders"\nversion = "0.1.0"',
				'name = "null3d-shaders"\nversion = "0.2.0"',
			),
		);
		expect(coreSourcesStamp(root)).not.toBe(whole);
		expect(inputHash(root, CORE_CRATE).slice(0, 16)).toBe(earlier);
		expect(coreFromOtherSources(root)).toBeNull();
	});

	it('refuses a core whose stamp belongs to other sources', () => {
		const root = checkout();
		const earlier = inputHash(root, CORE_CRATE).slice(0, 16);
		writeFileSync(join(root, 'crates/null3d-core/src/lib.rs'), 'pub const A: u32 = 1;\n');
		buildCore(root, earlier);
		expect(coreFromOtherSources(root)).toContain('the single engine core');
	});

	it('refuses a core that the checkout built from other sources', () => {
		const root = checkout();
		buildCore(root, '0123456789abcdef');
		const message = coreFromOtherSources(root);
		expect(message).toContain('the single engine core');
		expect(message).toContain('Run bun run build.');
	});

	it('refuses a core that no build wrote', () => {
		const root = checkout();
		buildCore(root, coreSourcesStamp(root));
		writeFileSync(join(root, 'packages/engine/dist/wasm/threaded/null3d.js'), 'export {};\n');
		expect(coreFromOtherSources(root)).toContain('the threaded engine core');
	});
});

describe('the accepted stamps', () => {
	it('holds one stamp when the lock cannot resolve the core closure', () => {
		// Both stamps read the whole file then, so the set collapses. It holds two only when the
		// lock resolves the closure and an entry outside it could differ.
		const root = checkout();
		writeFileSync(join(root, 'Cargo.lock'), 'version = 4\n');
		expect(inputHash(root, CORE_CRATE).slice(0, 16)).toBe(coreSourcesStamp(root));
		expect(acceptedSourcesStamps(root)).toEqual([coreSourcesStamp(root)]);
	});
});

describe('a build that packs or ships the core', () => {
	it('stops with the message that names bun run build', () => {
		const root = checkout();
		buildCore(root, '0123456789abcdef');
		expect(() => refuseStaleCore(root)).toThrow('Run bun run build.');
	});

	it('passes a core that this checkout built', () => {
		const root = checkout();
		buildCore(root, coreSourcesStamp(root));
		expect(() => refuseStaleCore(root)).not.toThrow();
	});

	it('asks nothing of a project that installs the engine package', () => {
		const root = fixture({ 'package.json': '{ "name": "a project" }\n' });
		expect(coreFromOtherSources(root)).toBeNull();
		expect(() => refuseStaleCore(root)).not.toThrow();
	});
});
